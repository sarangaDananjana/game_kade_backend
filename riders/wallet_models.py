"""Auditable prepaid funds, kept separate from earnings and penalties."""
import uuid
from decimal import Decimal
from django.conf import settings
from django.core.validators import MinValueValidator
from django.db import models


class RiderTopUp(models.Model):
    rider = models.ForeignKey('riders.RiderInfo', on_delete=models.PROTECT, related_name='topups')
    request_id = models.UUIDField(default=uuid.uuid4, unique=True, editable=False)
    amount = models.DecimalField(max_digits=10, decimal_places=2, validators=[MinValueValidator(Decimal('0.01'))])
    payment_reference = models.CharField(max_length=100, unique=True, default=uuid.uuid4, help_text='Optional collection receipt/reference; a unique reference is generated by default.')
    status = models.CharField(max_length=12, choices=[('pending', 'Pending'), ('approved', 'Approved'), ('rejected', 'Rejected')], default='pending')
    staff_note = models.CharField(max_length=250, blank=True)
    reviewed_by = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.PROTECT, null=True, blank=True, related_name='+')
    reviewed_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at', '-pk']
        constraints = [models.CheckConstraint(condition=models.Q(amount__gt=0), name='riders_topup_amount_positive')]


class RiderWalletEntry(models.Model):
    rider = models.ForeignKey('riders.RiderInfo', on_delete=models.PROTECT, related_name='wallet_entries')
    kind = models.CharField(max_length=12, choices=[('topup', 'Top up'), ('job_fee', 'Job acceptance fee')])
    amount = models.DecimalField(max_digits=12, decimal_places=2, help_text='Signed LKR change to the balance.')
    balance_after = models.DecimalField(max_digits=12, decimal_places=2)
    topup = models.OneToOneField(RiderTopUp, on_delete=models.PROTECT, null=True, blank=True)
    offer = models.OneToOneField('riders.JobOffer', on_delete=models.PROTECT, null=True, blank=True)
    session_reference = models.PositiveBigIntegerField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ['-created_at', '-pk']
        constraints = [
            models.CheckConstraint(condition=models.Q(balance_after__gte=0), name='riders_wallet_balance_positive'),
            models.CheckConstraint(condition=(models.Q(kind='topup', amount__gt=0, topup__isnull=False, offer__isnull=True)
                | models.Q(kind='job_fee', amount__lte=0, topup__isnull=True, offer__isnull=False)), name='riders_wallet_entry_source'),
        ]


class RiderRoadRoute(models.Model):
    """Shared geometry cache and lease, safe across web processes."""
    key = models.CharField(max_length=64, primary_key=True)
    payload = models.JSONField(default=dict)
    expires_at = models.DateTimeField(null=True, blank=True)
    lease_until = models.DateTimeField(null=True, blank=True)
    updated_at = models.DateTimeField(auto_now=True)
